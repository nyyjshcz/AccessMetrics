export type MessageKey = keyof (typeof messages)[typeof DEFAULT_LOCALE];

export function isLocale(value: unknown): value is Locale {
  return value === "zh-CN" || value === "en";
}

export function normalizeLocale(value: unknown): Locale {
  return isLocale(value) ? value : DEFAULT_LOCALE;
}

/** Resolve a request locale. An explicit URL value wins over the cookie. */
export function resolveLocale(urlLocale: unknown, cookieLocale?: unknown): Locale {
  return isLocale(urlLocale) ? urlLocale : normalizeLocale(cookieLocale);
}

export function getMessages(locale: Locale = DEFAULT_LOCALE) {
  return { ...messages[locale], homeDimensions: homeDimensions[locale] };
}

export function t(locale: Locale, key: MessageKey): string {
  const value = messages[locale][key] ?? messages[DEFAULT_LOCALE][key];
  return typeof value === "string" ? value : String(value);
}
